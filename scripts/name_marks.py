LABEL = {'otter': 'かわうそ'}


def main():
    sp = json.load(open('web/data/spots.json', encoding='utf-8'))['spots']
    out = {}
    for x in sp:
        name = NOT.sub('', x[1])
        ms = []
        for rx, m in WRE:
            h = rx.search(name)
            if h and m not in [a for a, _ in ms]:
                ms.append((m, h.group(0)))
            if len(ms) == 2:
                break
        if ms:
            out[f"{x[1]}|{x[2]}|{x[3]}"] = {'spec': [x[0], {}, [m for m, _ in ms]], 'why': '名前に「' + '」「'.join(w for _, w in ms) + '」'}
    json.dump(out, open(OUT, 'w', encoding='utf-8'), ensure_ascii=False, indent=0)
    print('名前から目印', len(out))


if __name__ == '__main__':
    main()
